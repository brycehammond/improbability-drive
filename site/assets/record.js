/**
 * The permalink page. /r/<id> -> GET /api/reports/<id> -> the compact card.
 * `?mock=1` renders the sample report instead.
 */
import { el, longDate, renderCard } from './card.js';

const when = document.getElementById('when');
const witness = document.getElementById('witness');
const stage = document.getElementById('record');

const WITNESSES = [
  'Witnessed by three passing dolphins · so long, and thanks',
  'Countersigned by a bowl of petunias',
  'Entered into the record by a mildly surprised kettle',
  'Verified against the 1974 revision',
];

function notFound() {
  when.textContent = 'There is no such record.';
  witness.textContent = 'It may never have occurred';
  stage.replaceChildren(
    el('article', { class: 'card is-note' }, [
      el('p', { class: 'event', text: 'The Drive has no report under that number.' }),
      el('p', { class: 'note-body', text: 'Either the link has been mistyped, or the event was so improbable that it failed to be filed. Both happen.' }),
    ]),
  );
}

async function load() {
  const mock = new URLSearchParams(location.search).has('mock');
  const id = location.pathname.replace(/^\/r\/?/, '').split('/')[0];
  let report = null;
  try {
    if (mock) {
      report = (await (await fetch('/assets/mock.json')).json()).random;
    } else if (id) {
      const res = await fetch(`/api/reports/${encodeURIComponent(id)}`);
      if (res.ok) report = await res.json();
    }
  } catch { /* handled as not found */ }

  if (!report?.event) return notFound();

  const permalink = `${location.origin}/r/${report.id ?? id}`;
  when.textContent = `Generated by the Improbability Drive on ${longDate(report.date)}.`;
  witness.textContent = WITNESSES[(report.reportNo ?? '').split('').reduce((a, c) => a + c.charCodeAt(0), 0) % WITNESSES.length];
  stage.replaceChildren(renderCard(report, { compact: true, permalink }));
  document.title = `${report.event} · The Improbability Drive`;
}

load();
